#!/bin/bash
set -e

GREEN='\033[0;32m' && YELLOW='\033[1;33m' && RED='\033[0;31m' && NC='\033[0m'

echo -e "${GREEN}=========================================================="
echo "    Модуль: Ленивое обновление физической карты (A-записи)"
echo -e "==========================================================${NC}"
echo ""

if [ "$EUID" -ne 0 ]; then
    echo -e "${RED}❌ Ошибка: Запустите скрипт под root (su - или sudo bash)!${NC}"
    exit 1
fi

FINAL_HOSTS="/etc/dnsmasq.hosts"

# 1. Интерактивный ввод новых A-записей
echo -e "${YELLOW}=== Перезапись физической карты сети ===${NC}"
echo "Вставьте или введите НОВЫЕ локальные IP ваших серверов."
echo "Формат: IP_АДРЕС  ИМЯ_НОДЫ.lab"
echo "----------------------------------------------------------"
echo -e "Пример ввода:\n192.168.2.2    underground-01.lab\n192.168.2.3    underground-03.lab"
echo "----------------------------------------------------------"
echo "Вносите данные ниже и нажмите Ctrl+D, когда закончите:"
echo "----------------------------------------------------------"

# Перехватываем ввод и намертво перезаписываем файл хостов
cat > "$FINAL_HOSTS"

# Проверяем, что файл не пустой
if [ ! -s "$FINAL_HOSTS" ]; then
    echo -e "${RED}❌ Ошибка: Вы ничего не ввели! Изменения отменены.${NC}"
    exit 1
fi

# 2. Мягкая перезагрузка таблиц в памяти dnsmasq
echo ""
echo "=== Мгновенное обновление таблиц в памяти DNS... ==="
if killall -HUP dnsmasq 2>/dev/null || pkill -HUP dnsmasq 2>/dev/null; then
    echo -e "${GREEN}🎉 Физическая карта сети успешно обновлена в фоне!${NC}"
    echo "----------------------------------------------------------"
    echo "Текущие активные A-записи в бункере:"
    cat "$FINAL_HOSTS"
    echo "----------------------------------------------------------"
else
    echo -e "${RED}⚠️ Ошибка: dnsmasq не запущен. Выполните полную установку через setup.sh${NC}"
    exit 1
fi
